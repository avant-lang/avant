#!/usr/bin/env python3
"""Regenerates every table of bench/valk from the raw files.

  python3 tables.py OUT [SESSION]

OUT is the directory run.sh wrote ($VALK_BENCH_OUT): rows.tsv,
versions.txt, build/, check/, counts/instructions.tsv, shipped/ (Valk's
own run.sh) and time/<session>/round-<r>/<id>.run (one file per run).
SESSION defaults to the one named in time/latest. Writes OUT/tables.md
and prints its path. A part whose raw files are missing is left out and
said so; nothing is taken from anywhere but the raw files.
"""
import glob
import os
import statistics
import sys

PROGRAMS = ["binary-tree", "merkletrees", "lru", "json", "json-serde", "nsieve", "spectral-norm", "fannkuch-redux"]
SET_TITLES = {
    "switch": "Valk's switch: `--no-regions` (every object on the collector's heap)",
    "levelled": "Levelled twins of a few lines (`variants/`): Valk doing what Go's and Rust's programs do",
    "v3": "Every compiler told to target x86-64-v3 (`--cpu x86-64-v3`, `GOAMD64=v3`, `-C target-cpu=x86-64-v3`)",
    "lto": "Rust with fat LTO and one code-generation unit",
}


def base_of(row):
    """The shipped row a variant is compared with."""
    if row.endswith("-v3"):
        return row[:-3]
    return row.split("-")[0]


def read_tsv(path, skip=0):
    with open(path) as f:
        return [line.rstrip("\n").split("\t") for line in f][skip:]


def fmt_int(n):
    return "{:,}".format(n)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    rows = [dict(zip(["id", "program", "row", "set", "binary", "cwd", "args"], r))
            for r in read_tsv(os.path.join(out, "rows.tsv"))]
    by_id = {r["id"]: r for r in rows}
    md = []
    add = md.append

    add("# Valk's general suite, tier 1, on this machine: tables")
    add("")
    add("Regenerated by `python3 bench/valk/tables.py <out>` from the raw files; nothing here is typed by hand. Valk's published numbers (another machine) are in no table.")
    add("")
    vpath = os.path.join(out, "versions.txt")
    if os.path.exists(vpath):
        add("## Toolchains and machine (`versions.txt`)")
        add("")
        add("```")
        md.extend(open(vpath).read().rstrip("\n").split("\n"))
        add("```")
        add("")
    add("## Rows and arguments (`rows.tsv`)")
    add("")
    add("| Program | Arguments | Rows |")
    add("| --- | --- | --- |")
    for p in PROGRAMS:
        rs = [r for r in rows if r["program"] == p]
        if rs:
            add("| `%s` | `%s` | %s |" % (p, rs[0]["args"], ", ".join(r["row"] for r in rs)))
    add("")

    # ---- outputs -----------------------------------------------------------
    cpath = os.path.join(out, "check", "summary.tsv")
    if os.path.exists(cpath):
        chk = read_tsv(cpath, 1)
        bad = [c for c in chk if c[3] != "ok"]
        add("## Outputs (`check/summary.tsv`)")
        add("")
        add("%d rows run once, untimed; %d differ from `expected/<program>.txt`%s. The expected file of each program is one file for every language and variant, so a row that passes printed the same bytes as the other languages." %
            (len(chk), len(bad), "" if not bad else ": " + ", ".join(c[0] for c in bad)))
        add("")

    # ---- Valk's own run.sh ---------------------------------------------------
    spath = os.path.join(out, "shipped", "run-sh.stdout")
    if os.path.exists(spath):
        add("## Table 1. As shipped: Valk's own `run.sh`, unchanged")
        add("")
        add("Valk's method: one warm-up, the median of N fresh processes by GNU time's `%e` (hundredths of a second) and `%M`, Valk always first. The session:")
        add("")
        add("```")
        md.extend(open(os.path.join(out, "shipped", "session.txt")).read().rstrip("\n").split("\n"))
        add("```")
        add("")
        md.extend(l for l in open(spath).read().strip("\n").split("\n"))
        add("")
        warn = [l for l in open(os.path.join(out, "shipped", "run-sh.stderr")).read().split("\n")
                if "arning" in l or "differs" in l or "nstable" in l]
        add("Warnings from `run.sh` (output differences between languages, unstable outputs): %s." % ("; ".join(warn) if warn else "none"))
        add("")
    else:
        add("## Table 1. As shipped: Valk's own `run.sh`, unchanged")
        add("")
        add("Not run yet (no `shipped/run-sh.stdout`).")
        add("")

    # ---- instruction counts --------------------------------------------------
    instr = {}
    ipath = os.path.join(out, "counts", "instructions.tsv")
    if os.path.exists(ipath):
        instr = {r[0]: int(r[1]) for r in read_tsv(ipath, 1)}

    # ---- timed session -------------------------------------------------------
    session = sys.argv[2] if len(sys.argv) > 2 else None
    latest = os.path.join(out, "time", "latest")
    if session is None and os.path.exists(latest):
        session = open(latest).read().strip()
    runs = {}
    disturbed = False
    if session:
        sdir = os.path.join(out, "time", session)
        for path in glob.glob(os.path.join(sdir, "round-*", "*.run")):
            rec = dict(line.rstrip("\n").split("\t", 1) for line in open(path))
            if rec.get("output") != "ok" or rec.get("exit") != "0":
                sys.exit("not a result: %s" % path)
            runs.setdefault(rec["id"], []).append(rec)
        stext = open(os.path.join(sdir, "session.txt")).read()
        disturbed = "DISTURBED" in stext

    def stats(rid):
        rs = runs.get(rid)
        if not rs:
            return None
        walls = sorted(int(r["wall_ns"]) / 1e9 for r in rs)
        rss = statistics.median(int(r["rss_kb"]) for r in rs) / 1024
        return {"n": len(rs), "med": statistics.median(walls), "min": walls[0], "max": walls[-1], "rss": rss}

    def time_cells(rid, base_id):
        s = stats(rid)
        if not s:
            return ["—"] * 6
        b = stats(base_id) if base_id else None
        ratio = "%.3f" % (s["med"] / b["med"]) if b and base_id != rid else ("1" if b else "—")
        return ["%.4f" % s["med"], "%.4f" % s["min"], "%.4f" % s["max"],
                "%.1f" % ((s["max"] - s["min"]) / s["med"] * 100), "%.1f" % s["rss"], ratio]

    def instr_cells(rid, base_id):
        if rid not in instr:
            return ["—", "—"]
        ratio = "%.3f" % (instr[rid] / instr[base_id]) if base_id in instr and base_id != rid else ("1" if base_id in instr else "—")
        return [fmt_int(instr[rid]), ratio]

    mark = " — **DISTURBED, NOT EVIDENCE** (a dry run beside other work; the numbers prove the runner, nothing else)" if disturbed else ""
    add("## Table 2. The shipped programs by this workbench's method%s" % mark)
    add("")
    if session:
        add("Session `%s` (`time/%s/session.txt`):" % (session, session))
        add("")
        add("```")
        md.extend(stext.rstrip("\n").split("\n"))
        add("```")
        add("")
        add("Seconds are wall time by a nanosecond clock around the process; median, minimum and maximum of the measured rounds (never a best-of); spread is (max − min) / median. Peak RSS is the median of GNU time's `%M`. `× Valk` divides by the Valk row of the same program. Instructions are `perf stat -e instructions:u` of one separate run, all threads of the process (Go's collector runs on other threads, so its count is not its wall time).")
    else:
        add("No timed session yet: the time columns are empty. Instructions are `perf stat -e instructions:u` of one run, all threads of the process (Go's collector runs on other threads, so its count is not its wall time).")
    add("")
    head = "| Program | Row | Median s | Min s | Max s | Spread % | Peak RSS MB | × Valk time | Instructions:u | × Valk instr. |"
    sep = "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
    add(head)
    add(sep)
    for p in PROGRAMS:
        for r in rows:
            if r["program"] == p and r["set"] == "shipped":
                base = p + ":valk"
                add("| `%s` | %s | %s | %s |" % (p, r["row"], " | ".join(time_cells(r["id"], base)), " | ".join(instr_cells(r["id"], base))))
    add("")

    # rows within 5% of each other
    add("### Shipped rows within 5% of each other in time (the pairs instruction counts must separate)")
    add("")
    if session:
        close = []
        for p in PROGRAMS:
            rs = [r for r in rows if r["program"] == p and r["set"] == "shipped" and stats(r["id"])]
            for i in range(len(rs)):
                for j in range(i + 1, len(rs)):
                    a, b = stats(rs[i]["id"]), stats(rs[j]["id"])
                    d = abs(a["med"] - b["med"]) / min(a["med"], b["med"])
                    if d <= 0.05:
                        ia, ib = instr.get(rs[i]["id"]), instr.get(rs[j]["id"])
                        close.append("| `%s` | %s / %s | %.4f / %.4f | %.1f | %s / %s | %s |" % (
                            p, rs[i]["row"], rs[j]["row"], a["med"], b["med"], d * 100,
                            fmt_int(ia) if ia else "—", fmt_int(ib) if ib else "—",
                            "%.3f" % (ib / ia) if ia and ib else "—"))
        if close:
            add("| Program | Rows | Median s | Difference % | Instructions:u | Second / first |")
            add("| --- | --- | ---: | ---: | ---: | ---: |")
            md.extend(close)
        else:
            add("None.")
    else:
        add("Needs a timed session.")
    add("")

    # the rounds: is one of them disturbed, and which rows vary
    if session:
        add("### The rounds (a disturbed round would stand out across all rows)")
        add("")
        add("For each round, over all rows: this round's wall time divided by the row's median over the rounds.")
        add("")
        add("| Round | Median ratio | Min | Max | Rows more than 3% above their median |")
        add("| ---: | ---: | ---: | ---: | ---: |")
        nrounds = max(int(r["round"]) for rs in runs.values() for r in rs)
        for rd in range(1, nrounds + 1):
            ratios = []
            for rid, rs in runs.items():
                med = statistics.median(int(r["wall_ns"]) for r in rs)
                ratios.extend(int(r["wall_ns"]) / med for r in rs if int(r["round"]) == rd)
            add("| %d | %.4f | %.4f | %.4f | %d |" % (rd, statistics.median(ratios), min(ratios), max(ratios),
                                                  sum(1 for x in ratios if x > 1.03)))
        add("")
        wide = []
        for r in rows:
            s = stats(r["id"])
            if s and (s["max"] - s["min"]) / s["med"] > 0.05:
                walls = sorted(runs[r["id"]], key=lambda x: int(x["round"]))
                wide.append("| `%s` | %s |" % (r["id"], " ".join("%.4f" % (int(x["wall_ns"]) / 1e9) for x in walls)))
        add("Rows with a spread over 5%, their wall times in round order:")
        add("")
        if wide:
            add("| Row | Seconds, rounds 1 to %d |" % nrounds)
            add("| --- | --- |")
            md.extend(wide)
        else:
            add("None.")
        add("")

    # ---- variants ------------------------------------------------------------
    add("## Table 3. Labelled variants%s" % mark)
    add("")
    add("Each variant is compared with the shipped row of the same language (`× shipped`). None of these rows is a headline row.")
    add("")
    for s in ["switch", "levelled", "v3", "lto"]:
        vs = [r for r in rows if r["set"] == s]
        if not vs:
            continue
        add("### %s" % SET_TITLES[s])
        add("")
        add("| Program | Row | Median s | Min s | Max s | Spread % | Peak RSS MB | × shipped time | Instructions:u | × shipped instr. |")
        add(sep)
        for p in PROGRAMS:
            for r in vs:
                if r["program"] == p:
                    base = p + ":" + base_of(r["row"])
                    if base not in by_id:
                        sys.exit("no shipped row for %s" % r["id"])
                    add("| `%s` | %s (against %s) | %s | %s |" % (p, r["row"], base_of(r["row"]),
                                                                " | ".join(time_cells(r["id"], base)), " | ".join(instr_cells(r["id"], base))))
        add("")

    # ---- builds --------------------------------------------------------------
    bpath = os.path.join(out, "build", "commands.txt")
    if os.path.exists(bpath):
        add("## Build commands (`build/commands.txt`; binaries' sha256 in `build/sha256.txt`)")
        add("")
        add("```")
        for line in open(bpath).read().rstrip("\n").split("\n"):
            add(line)
        add("```")
        add("")

    path = os.path.join(out, "tables.md")
    with open(path, "w") as f:
        f.write("\n".join(md) + "\n")
    print(path)


if __name__ == "__main__":
    main()
